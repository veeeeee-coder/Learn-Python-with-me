#fundamental data types in python
#1. int- whole numbers
#2. float- decimal numbers
#3. str- sequence of characters
#4. bool- True or False
#5. NoneType- represents the absence of a value
age=12
print(type(age))

pi=3.14
print(type(pi))

name="vee"
print(type(name))

is_student=True
print(type(is_student))

a=None
print(type(a))


#output is
#<class 'int'>
#<class 'float'>
#<class 'str'>
#<class 'bool'>
#<class 'NoneType'>